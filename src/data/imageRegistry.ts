export function getSemanticImage(keyOrKeyword: string, fallback?: string): string {
  if (!keyOrKeyword || typeof keyOrKeyword !== 'string') return fallback || SEMANTIC_IMAGES.flower || SEMANTIC_IMAGES.candle;
  const cleanKey = keyOrKeyword.toLowerCase().trim().replace(/[^a-z0-9_]/g, '_');

  if (SEMANTIC_IMAGES[cleanKey]) {
    return SEMANTIC_IMAGES[cleanKey];
  }

  // Substring match
  for (const [k, url] of Object.entries(SEMANTIC_IMAGES)) {
    if (cleanKey.includes(k) || k.includes(cleanKey)) {
      return url;
    }
  }

  return fallback || SEMANTIC_IMAGES.candle;
}
